import assert from 'node:assert/strict';
import auth from '../api/auth.js'; import op from '../api/op.js'; import board from '../api/board.js'; import photo from '../api/photo.js';
const NAMES = { 11111111: 'loriale', 22222222: 'ben', 33333333: 'mayer', 12345678: 'ben' };
const login = async (pin) => { const r = await auth.fetch(new Request('https://x/api/auth', { method: 'POST', body: JSON.stringify({ username: NAMES[pin], password: pin }) })); return { status: r.status, body: await r.json(), cookie: (r.headers.get('set-cookie') || '').split(';')[0] }; };
const post = (c, b) => op.fetch(new Request('https://x/api/op', { method: 'POST', headers: { cookie: c, 'content-type': 'application/json' }, body: JSON.stringify(b) })).then((r) => r.json());
const L = await login('11111111'); assert.equal(L.body.name, 'Loriale');
const B = await login('22222222'); assert.equal(B.body.name, 'Ben');
assert.equal((await login('12345678')).status, 401);
const c = await post(B.cookie, { by: 'Mayer', op: 'create', data: { type: 'estimate', assignee: 'Loriale', customer: 'Smith', description: 'x'.repeat(800) } });
assert.equal(Object.values(c.board.tasks)[0].createdBy, 'Ben', 'author comes from cookie');
const id = c.result.id;
await Promise.all([1, 2, 3, 4, 5].map((i) => post(L.cookie, { op: 'note', id, text: 'note ' + i })));
const s = await post(L.cookie, { op: 'status', id, status: 'progress' });
assert.ok(s.ok, 'status change saves');
const forged = 'rs_user=' + Buffer.from('Mayer').toString('base64url') + '.' + 'a'.repeat(64);
assert.equal((await board.fetch(new Request('https://x/api/board', { headers: { cookie: forged } }))).status, 401);
const r = await photo.fetch(new Request('https://x/api/photo?taskId=' + id, { method: 'POST', headers: { cookie: B.cookie, 'content-type': 'image/jpeg' }, body: new Uint8Array([1, 2]) }));
assert.equal(Object.values((await r.json()).board.photos)[0].by, 'Ben');
const all = await (await board.fetch(new Request('https://x/api/board', { headers: { cookie: L.cookie } }))).json();
assert.equal(Object.values(all.notes).filter((x) => x.kind === 'note').length, 5, 'no simultaneous notes lost');
const d = await post(L.cookie, { op: 'delete', id });
assert.equal(Object.keys(d.board.tasks).length + Object.keys(d.board.photos).length, 0);
console.log('all checks passed');
